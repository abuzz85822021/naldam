WORLD_HISTORY = {}


# =========================================================
# 사건 추가 함수
# =========================================================

def add_event(
    month,
    day,
    year,
    country,
    title,
    description,
    importance=1,
    category="기타",
    why=""
):

    key = (month, day)

    if key not in WORLD_HISTORY:
        WORLD_HISTORY[key] = []

    WORLD_HISTORY[key].append(
        {
            "year": year,
            "country": country,
            "title": title,
            "description": description,
            "importance": importance,
            "category": category,
            "why": why,
        }
    )


