KOREA_HISTORY = {}


# =========================================================
# 사건 추가 함수
# =========================================================

def add_event(
    month,
    day,
    year,
    title,
    description,
    importance=1,
    category="기타",
    why="",
    date_type="양력",
    original_date=""
):
    key = (month, day)

    if key not in KOREA_HISTORY:
        KOREA_HISTORY[key] = []

    KOREA_HISTORY[key].append(
        {
            "year": year,
            "title": title,
            "description": description,
            "importance": importance,
            "category": category,
            "why": why,
            "date_type": date_type,
            "original_date": original_date,
        }
    )

